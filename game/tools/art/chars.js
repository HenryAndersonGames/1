// ---------- Кадры ----------
function playerFrame(i, ph, moving) {
  const c = PAL[i];
  const s = moving ? Math.sin(ph) : 0, bob = moving ? -Math.abs(Math.cos(ph)) * 2.2 : 0;
  const la = s * 26, aa = -s * 22;
  let out = '';
  out += g(`translate(-4 ${f(-45.5 + bob)}) rotate(${f(aa + 6)})`, arm(c, true));
  out += g(`translate(-2 -22) rotate(${f(-la)})`, leg(c, true));
  out += g(`translate(2 -22) rotate(${f(la)})`, leg(c, false));
  out += g(`translate(0 ${f(-22 + bob)})`, torso(c, i));
  out += g(`translate(1.6 ${f(-47 + bob)})`, head(c, i));
  return svg(-28, -90, 56, 96, out);
}
function build(out) {
  for (let i = 0; i < 2; i++) {
    for (let k = 0; k < 4; k++) out[`p${i}_walk${k}`] = playerFrame(i, k / 4 * Math.PI * 2, true);
    out[`p${i}_idle`] = playerFrame(i, 0, false);
    out[`p${i}_arm`] = svg(-7, -6, 14, 30, arm(PAL[i], false));
    out[`p${i}_head`] = svg(-20, -44, 42, 50, head(PAL[i], i));
  }
  out.bat = svg(-5, -8, 47, 16, bat());
}
module.exports = { build, PAL };
