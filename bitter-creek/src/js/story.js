export function ending(g) {
  const s = g.state;
  const alive = g.npcs.filter(n => n.alive && !n.hollow).length;
  const total = g.npcs.length;
  const lost = total - alive;
  const innocents = s.innocents;
  const docFate = s.flags.docDied ? 'Доктора Холта похоронили на кладбище, рядом с пустой могилой дочери. Мортон не взял за работу ни цента.' : 'Доктора Холта больше никто не видел. Говорят, в Тусоне появился седой человек, который каждый вечер рисует углём лошадей.';
  if (s.flags.lost) {
    return {
      title: 'Чёрная луна',
      lines: [
        'На седьмую ночь луна не взошла. Вместо неё над Биттер-Криком повисла дыра — темнее неба.',
        'Земля под городом вздохнула. Один раз. Глубоко.',
        'Утром дилижанс из Тусона въехал на главную улицу. Двери домов были открыты. На столах стоял остывший ужин.',
        'В салуне кто-то играл на пианино. Одну и ту же ноту. Снова и снова.',
        'Кучер не стал выходить. Он развернул лошадей и гнал до самого Тусона.',
        'Агентство Холлоуэя внесло ваши имена в список пропавших без вести.',
      ],
    };
  }
  const L = [];
  L.push('Сердце Голодного горело до рассвета. Чёрный дым стелился над лесом, пока ветер не разорвал его в клочья.');
  L.push('Утром Пустые не вернулись в город. Их дома так и стояли открытыми.');
  L.push(docFate);
  if (innocents >= 2) {
    L.push(`Но в Биттер-Крике запомнили и другое. ${innocents} человек погибли от ваших пуль — потому что вам «показалось».`);
    L.push('Город спасли. Город вас не простил. Когда дилижанс тронулся, в его стенку ударил камень. Потом второй.');
    return { title: 'Спасители с кровью на руках', lines: L.concat([`Выжило ${alive} из ${total} жителей.`]) };
  }
  if (alive < 10) {
    L.push(`Мортон сколотил ${lost} гробов. Большинство из них остались пустыми.`);
    L.push('Город не пережил зиму. Весной последние жители уехали в Тусон. Ветер гоняет перекати-поле по главной улице.');
    return { title: 'Пепел', lines: L.concat([`Выжило ${alive} из ${total} жителей.`]) };
  }
  L.push(lost > 0 ? `Мортон сколотил ${lost} гробов — и впервые за полгода напился.` : 'Мортону в этот раз было некого хоронить. Он напился от радости.');
  L.push('Шериф Коул отправил в агентство телеграмму из трёх слов: «Дело закрыто. Спасибо».');
  L.push('Вы уехали дневным дилижансом. Никто не вышел провожать. Но из каждого окна на вас смотрели.');
  L.push('Живые.');
  return { title: 'Рассвет над Биттер-Криком', lines: L.concat([`Выжило ${alive} из ${total} жителей.`]) };
}
